static void ModLog(const wchar_t* fmt, ...)
{
    wchar_t b[512];
    va_list a;
    va_start(a, fmt);
    _vsnwprintf(b, 511, fmt, a);
    va_end(a);
    b[511] = 0;
    Wh_Log(L"%s", b);
    HANDLE h = CreateFileW(L"C:\\Temp\\wh\\nvc-styler-mod.log", FILE_APPEND_DATA,
                           FILE_SHARE_READ | FILE_SHARE_WRITE, nullptr, OPEN_ALWAYS, 0, nullptr);
    if (h == INVALID_HANDLE_VALUE) return;
    char u[1024];
    int n = WideCharToMultiByte(CP_UTF8, 0, b, -1, u, 1020, nullptr, nullptr);
    if (n > 0) { u[n - 1] = '\n'; DWORD w; WriteFile(h, u, n, &w, nullptr); }
    CloseHandle(h);
}

